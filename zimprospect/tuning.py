"""Fuzzy weight tuning (U7): fit each commodity's evidence weights with honest spatial-block CV.

A weight only changes the exponent applied to one evidence membership inside the fuzzy
gamma operator, so every membership raster is computed once and a seeded random search
re-combines them. Cells are split into the same 50 km blocks the random forest uses and
whole blocks are dealt into folds. For each fold the weights with the best AUC on the
training-fold points (ranked against cells in training blocks) are chosen, then scored
on the held-out points against cells in held-out blocks. The expert prior is scored the
same way. Weights refitted on all points replace the prior only when the mean held-out
gain is at least MIN_GAIN. The expert config is never overwritten.
"""
from __future__ import annotations

import json
import logging
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

import geopandas as gpd
import numpy as np
import yaml

from . import models, occurrences
from .features import FeatureStack
from .fuzzy import fuzzy_gamma
from .grid import Grid

log = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
PROTECTED_CONFIG = ROOT / "config" / "commodities.yaml"
DEFAULT_CONFIG_OUT = ROOT / "config" / "commodities.tuned.yaml"
REPORT_NAME = "tuning_report.json"

WEIGHT_MIN = 0.3
WEIGHT_MAX = 1.0
WEIGHT_DECIMALS = 2           # candidates are rounded first, so the YAML holds exactly what was scored
DEFAULT_WEIGHT = 1.0          # evidence entries without `weight` act at full strength (as in models)
DEFAULT_BLOCK_KM = 50.0
DEFAULT_FOLDS = 5
DEFAULT_MAX_EVALS = 200
DEFAULT_SEED = 42
DEFAULT_MIN_TUNE_POINTS = 15
MIN_GAIN = 0.02               # mean held-out AUC gain needed to replace the expert prior
GAIN_TOLERANCE = 1e-9         # absorbs float error in the AUC difference
MIN_TRAIN_POINTS = 3          # same per-fold floor as models.random_forest
MAX_SEARCH_CELLS = 200_000    # background sample for the search; held-out AUCs use every cell
REPORT_DECIMALS = 4
YAML_WIDTH = 110

TUNED_HEADER = (
    "# Generated by `python -m zimprospect tune` from config/commodities.yaml. Do not edit by hand.\n"
    "# Commodities whose weights passed held-out spatial-block tuning carry them below (their\n"
    "# evidence lists are flattened); every other commodity keeps the expert prior. YAML anchors\n"
    "# are written out in full. See tuning_report.json in the output folder for the scores.\n\n"
)


@dataclass(frozen=True)
class TuneResult:
    prior_auc: float                    # mean held-out AUC of the config weights over scored folds
    tuned_auc: float                    # mean held-out AUC of the weights each fold's training data chose
    gain: float                         # tuned_auc - prior_auc
    accepted: bool                      # gain >= MIN_GAIN
    weights: tuple[float, ...]          # final weights: the all-points refit if accepted, else the prior
    prior_weights: tuple[float, ...] = ()
    refit_weights: tuple[float, ...] = ()
    n_points: int = 0
    fold_prior_auc: tuple[float, ...] = ()
    fold_tuned_auc: tuple[float, ...] = ()


@dataclass(frozen=True)
class FoldAUC:
    train: np.ndarray   # (folds,) training-fold points vs cells in training blocks (NaN = undefined)
    test: np.ndarray    # (folds,) held-out points vs cells in held-out blocks (NaN = undefined)
    overall: float      # all points vs all cells


@dataclass(frozen=True)
class _Cells:
    memberships: tuple[np.ndarray, ...]  # one 1-D membership vector per flattened evidence entry
    fold: np.ndarray                     # fold id of each cell
    points: np.ndarray                   # positions of the occurrence cells within this set


# ---------- folds and fast AUC ----------

def block_folds(stack: FeatureStack, block_km: float, folds: int,
                seed: int = models.RNG_SEED) -> np.ndarray:
    """Fold id of every in-mask cell (np.nonzero order); each block goes wholly to one fold.

    Uses models._block_ids and the random forest's scheme (seeded permutation of blocks, mod folds).
    """
    blocks = models._block_ids(stack, block_km)
    unique, inverse = np.unique(blocks, return_inverse=True)
    fold_of_block = np.random.default_rng(seed).permutation(unique.size) % folds
    return fold_of_block[inverse.ravel()]


def _rank_sums(scores: np.ndarray, fold: np.ndarray, levels: np.ndarray,
               folds: int) -> tuple[np.ndarray, np.ndarray]:
    """Per fold and level: #cells below it + #cells at or below it; plus the cells per fold.

    below = at_or_below - tied, so one searchsorted pass and a count of exact ties suffice.
    """
    n_levels = levels.size
    pos = np.searchsorted(levels, scores, side="left")   # number of levels strictly below each cell
    counts = np.bincount(fold * (n_levels + 1) + pos, minlength=folds * (n_levels + 1))
    at_or_below = np.cumsum(counts.reshape(folds, n_levels + 1), axis=1)[:, :n_levels]
    tied = (pos < n_levels) & (levels[np.minimum(pos, n_levels - 1)] == scores)
    ties = np.bincount(fold[tied] * n_levels + pos[tied], minlength=folds * n_levels)
    return 2 * at_or_below - ties.reshape(folds, n_levels), np.bincount(fold, minlength=folds)


def fold_aucs(scores: np.ndarray, fold: np.ndarray, points: np.ndarray, folds: int) -> FoldAUC:
    """validate.success_rate's AUC (ties count half) for every fold split at once.

    One pass over the cells: O(n log m) for m distinct point scores, no full sort.
    """
    valid = np.isfinite(scores)
    points = points[valid[points]]
    undefined = np.full(folds, np.nan)
    if points.size == 0:
        return FoldAUC(undefined, undefined, math.nan)
    pt_scores, pt_fold = scores[points], fold[points]
    levels = np.unique(pt_scores)
    sums, n_cells = _rank_sums(scores[valid], fold[valid], levels, folds)
    level = np.searchsorted(levels, pt_scores)
    total_sums, total_cells = sums.sum(axis=0), int(n_cells.sum())

    def test_auc(k: int) -> float:
        held = pt_fold == k
        return float(sums[k, level[held]].mean() / (2 * n_cells[k])) if held.any() else math.nan

    def train_auc(k: int) -> float:
        kept, n_train = pt_fold != k, total_cells - n_cells[k]
        if not kept.any() or n_train == 0:
            return math.nan
        return float((total_sums - sums[k])[level[kept]].mean() / (2 * n_train))

    return FoldAUC(train=np.array([train_auc(k) for k in range(folds)]),
                   test=np.array([test_auc(k) for k in range(folds)]),
                   overall=float(total_sums[level].mean() / (2 * total_cells)))


# ---------- search ----------

def candidate_weights(prior: Sequence[float], max_evals: int, rng: np.random.Generator) -> np.ndarray:
    """(max_evals, n_entries): row 0 is the expert prior, the rest uniform in [WEIGHT_MIN, WEIGHT_MAX]."""
    draws = rng.uniform(WEIGHT_MIN, WEIGHT_MAX, size=(max_evals - 1, len(prior)))
    return np.vstack([np.asarray(prior, dtype=float), np.round(draws, WEIGHT_DECIMALS)])


def accepts(gain: float, min_gain: float = MIN_GAIN) -> bool:
    """True when the held-out gain is large enough to replace the expert prior."""
    return bool(math.isfinite(gain) and gain >= min_gain - GAIN_TOLERANCE)


def _point_positions(mask: np.ndarray, rows: np.ndarray, cols: np.ndarray) -> np.ndarray:
    """Positions of occurrence cells in the in-mask cell vector (cells outside the mask dropped)."""
    position = np.cumsum(mask.ravel()).reshape(mask.shape) - 1
    inside = mask[rows, cols]
    return np.unique(position[rows[inside], cols[inside]])


def _subsample(cells: _Cells, limit: int, rng: np.random.Generator) -> _Cells:
    """A fixed random background sample plus every occurrence cell, to keep the search cheap."""
    n = cells.fold.size
    if n <= limit:
        return cells
    keep = np.union1d(rng.choice(n, size=limit, replace=False), cells.points)
    return _Cells(memberships=tuple(m[keep] for m in cells.memberships),
                  fold=cells.fold[keep], points=np.searchsorted(keep, cells.points))


def _score(cells: _Cells, weights: Sequence[float], gamma: float, folds: int) -> FoldAUC:
    scores = fuzzy_gamma(list(cells.memberships), gamma, [float(w) for w in weights])
    return fold_aucs(scores, cells.fold, cells.points, folds)


def _search(cells: _Cells, candidates: np.ndarray, gamma: float,
            folds: int) -> tuple[np.ndarray, np.ndarray]:
    """Training AUC per fold (n_candidates, folds) and all-points AUC (n_candidates,)."""
    results = [_score(cells, w, gamma, folds) for w in candidates]
    return np.array([r.train for r in results]), np.array([r.overall for r in results])


def _best(values: np.ndarray) -> int:
    """Index of the highest finite value; ties (and all-NaN) go to the earliest row, i.e. the prior."""
    return int(np.argmax(np.where(np.isfinite(values), values, -np.inf)))


def _scored_folds(point_fold: np.ndarray, folds: int) -> list[int]:
    """Folds with held-out points and enough training points to fit on."""
    counts = np.bincount(point_fold, minlength=folds)
    total = int(counts.sum())
    return [k for k in range(folds) if counts[k] > 0 and total - counts[k] >= MIN_TRAIN_POINTS]


def _held_out(cells: _Cells, candidates: np.ndarray, chosen: Mapping[int, int], gamma: float,
              folds: int) -> tuple[np.ndarray, np.ndarray]:
    """Held-out AUC per fold for the prior (row 0) and for each fold's chosen candidate."""
    needed = sorted(set(chosen.values()) | {0})
    test = {i: _score(cells, candidates[i], gamma, folds).test for i in needed}
    tuned = np.array([test[chosen[k]][k] if k in chosen else math.nan for k in range(folds)])
    return test[0], tuned


def _result(prior: tuple[float, ...], refit: tuple[float, ...], prior_test: np.ndarray,
            tuned_test: np.ndarray, n_points: int) -> TuneResult:
    both = np.isfinite(prior_test) & np.isfinite(tuned_test)
    prior_auc = float(prior_test[both].mean()) if both.any() else math.nan
    tuned_auc = float(tuned_test[both].mean()) if both.any() else math.nan
    gain = tuned_auc - prior_auc
    accepted = accepts(gain)
    return TuneResult(prior_auc=prior_auc, tuned_auc=tuned_auc, gain=gain, accepted=accepted,
                      weights=refit if accepted else prior, prior_weights=prior, refit_weights=refit,
                      n_points=n_points,
                      fold_prior_auc=tuple(float(x) for x in prior_test[both]),
                      fold_tuned_auc=tuple(float(x) for x in tuned_test[both]))


def _check_args(rows: np.ndarray, cols: np.ndarray, block_km: float, folds: int, max_evals: int) -> None:
    if len(rows) != len(cols):
        raise ValueError(f"rows and cols must have the same length ({len(rows)} vs {len(cols)})")
    if block_km <= 0:
        raise ValueError(f"block_km must be positive, got {block_km}")
    if folds < 2:
        raise ValueError(f"folds must be at least 2, got {folds}")
    if max_evals < 1:
        raise ValueError(f"max_evals must be at least 1, got {max_evals}")


def _membership(entry: Mapping[str, Any], stack: FeatureStack, class_names: Mapping[str, Sequence[str]] | None,
                mask: np.ndarray) -> np.ndarray:
    """Membership inside the mask; an optional layer that is absent counts as missing evidence (NaN)."""
    if not models._available(dict(entry), stack):
        return np.full(int(mask.sum()), np.nan)
    return models.evidence_layer(dict(entry), stack, class_names)[mask]


def tune_commodity(spec: Mapping[str, Any], stack: FeatureStack, rows: np.ndarray, cols: np.ndarray,
                   gamma: float, block_km: float = DEFAULT_BLOCK_KM, folds: int = DEFAULT_FOLDS,
                   max_evals: int = DEFAULT_MAX_EVALS, seed: int = DEFAULT_SEED,
                   class_names: Mapping[str, Sequence[str]] | None = None) -> TuneResult:
    """Tune one commodity's evidence weights; weights follow models._flatten(spec['evidence']) order."""
    rows, cols = np.asarray(rows, dtype=int), np.asarray(cols, dtype=int)
    _check_args(rows, cols, block_km, folds, max_evals)
    entries = models._flatten(spec["evidence"])
    prior = tuple(float(e.get("weight", DEFAULT_WEIGHT)) for e in entries)
    mask = stack.grid.mask
    full = _Cells(memberships=tuple(_membership(e, stack, class_names, mask) for e in entries),
                  fold=block_folds(stack, block_km, folds), points=_point_positions(mask, rows, cols))
    candidate_rng, cell_rng = (np.random.default_rng(s) for s in np.random.SeedSequence(seed).spawn(2))
    candidates = candidate_weights(prior, max_evals, candidate_rng)
    train, overall = _search(_subsample(full, MAX_SEARCH_CELLS, cell_rng), candidates, gamma, folds)
    chosen = {k: _best(train[:, k]) for k in _scored_folds(full.fold[full.points], folds)}
    prior_test, tuned_test = _held_out(full, candidates, chosen, gamma, folds)
    refit = tuple(float(w) for w in candidates[_best(overall)])
    return _result(prior, refit, prior_test, tuned_test, n_points=int(full.points.size))


# ---------- tuned config ----------

class _NoAliasDumper(yaml.SafeDumper):
    """Writes shared objects (YAML anchors in the source) out in full."""

    def ignore_aliases(self, data: Any) -> bool:
        return True


def _with_weights(key: str, spec: Mapping[str, Any], weights: Sequence[float]) -> dict[str, Any]:
    entries = models._flatten(spec["evidence"])
    if len(entries) != len(weights):
        raise ValueError(f"{key}: {len(weights)} weights for {len(entries)} evidence entries")
    return {**spec, "evidence": [{**e, "weight": float(w)} for e, w in zip(entries, weights)]}


TUNED_MARKER = "tuned_weights"  # run() reports these commodities' scores as optimistic


def tuned_config(cfg: Mapping[str, Any], weights: Mapping[str, Sequence[float]]) -> dict[str, Any]:
    """Copy of cfg in which each commodity named in `weights` carries those weights (inputs untouched)."""
    unknown = sorted(set(weights) - set(cfg["commodities"]))
    if unknown:
        raise ValueError(f"unknown commodities: {unknown}")
    commodities = {key: ({**_with_weights(key, spec, weights[key]), TUNED_MARKER: True} if key in weights else spec)
                   for key, spec in cfg["commodities"].items()}
    return {**cfg, "commodities": commodities}


def _guard_output(path: Path) -> None:
    if path.resolve() == PROTECTED_CONFIG.resolve():
        raise ValueError(f"refusing to overwrite the expert config {PROTECTED_CONFIG}; "
                         "write the tuned weights to a separate file")


def write_tuned_config(cfg: Mapping[str, Any], path: Path) -> None:
    _guard_output(path)
    text = yaml.dump(dict(cfg), Dumper=_NoAliasDumper, sort_keys=False,
                     default_flow_style=None, width=YAML_WIDTH)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(TUNED_HEADER + text)


# ---------- driver ----------

def _number(x: float) -> float | None:
    return round(float(x), REPORT_DECIMALS) if math.isfinite(x) else None


def _report_entry(spec: Mapping[str, Any], res: TuneResult) -> dict[str, Any]:
    layers = [e["layer"] for e in models._flatten(spec["evidence"])]
    return {"status": "accepted" if res.accepted else "kept_prior",
            "prior_auc": _number(res.prior_auc), "tuned_auc": _number(res.tuned_auc),
            "gain": _number(res.gain), "folds_scored": len(res.fold_prior_auc),
            "fold_prior_auc": [_number(x) for x in res.fold_prior_auc],
            "fold_tuned_auc": [_number(x) for x in res.fold_tuned_auc],
            "weights": [{"layer": name, "prior": p, "refit": r, "final": f}
                        for name, p, r, f in zip(layers, res.prior_weights, res.refit_weights, res.weights)]}


def _settings(cfg: Mapping[str, Any]) -> dict[str, Any]:
    return {"gamma": float(cfg["gamma"]),
            "block_km": float(cfg.get("spatial_block_km", DEFAULT_BLOCK_KM)),
            "folds": DEFAULT_FOLDS, "max_evals": DEFAULT_MAX_EVALS, "seed": DEFAULT_SEED,
            "min_tune_points": int(cfg.get("min_tune_points", DEFAULT_MIN_TUNE_POINTS)),
            "min_gain": MIN_GAIN, "weight_range": [WEIGHT_MIN, WEIGHT_MAX],
            "max_search_cells": MAX_SEARCH_CELLS}


def _tune_one(key: str, spec: Mapping[str, Any], stack: FeatureStack, occ: gpd.GeoDataFrame,
              grid: Grid, settings: Mapping[str, Any],
              class_names: Mapping[str, Sequence[str]] | None = None) -> tuple[dict[str, Any], TuneResult | None]:
    pts = occurrences.select(occ, spec["match"])
    rows, cols = occurrences.decluster(pts, grid)
    base = {"label": spec.get("label", key), "occurrences": int(len(pts)), "points": int(len(rows))}
    if len(rows) < settings["min_tune_points"]:
        log.info("%-13s skipped: %d declustered points < %d", key, len(rows), settings["min_tune_points"])
        return {**base, "status": "skipped",
                "reason": f"fewer than {settings['min_tune_points']} declustered points"}, None
    res = tune_commodity(spec, stack, rows, cols, settings["gamma"], settings["block_km"],
                         settings["folds"], settings["max_evals"], settings["seed"], class_names)
    log.info("%-13s prior %.3f -> tuned %.3f (gain %+.3f over %d folds): %s", key, res.prior_auc,
             res.tuned_auc, res.gain, len(res.fold_prior_auc), "accepted" if res.accepted else "kept prior")
    return {**base, **_report_entry(spec, res)}, res


def run_tuning(cfg: Mapping[str, Any], stack: FeatureStack, occ: gpd.GeoDataFrame, grid: Grid,
               out_dir: Path, config_out: Path = DEFAULT_CONFIG_OUT,
               only: Sequence[str] | None = None,
               class_names: Mapping[str, Sequence[str]] | None = None) -> dict[str, Any]:
    """Tune every eligible commodity; write out_dir/tuning_report.json and the tuned config copy."""
    out_dir, config_out = Path(out_dir), Path(config_out)
    _guard_output(config_out)
    unknown = sorted(set(only or ()) - set(cfg["commodities"]))
    if unknown:
        raise ValueError(f"unknown commodity keys: {unknown}")
    settings = _settings(cfg)
    keys = [k for k in cfg["commodities"] if not only or k in only]
    outcomes = {k: _tune_one(k, cfg["commodities"][k], stack, occ, grid, settings, class_names) for k in keys}
    report = {"settings": settings, "config_out": str(config_out),
              "commodities": {k: entry for k, (entry, _) in outcomes.items()}}
    accepted = {k: res.weights for k, (_, res) in outcomes.items() if res is not None and res.accepted}
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / REPORT_NAME).write_text(json.dumps(report, indent=2))
    write_tuned_config(tuned_config(cfg, accepted), config_out)
    log.info("tuning report written to %s; tuned config to %s (%d of %d commodities changed)",
             out_dir / REPORT_NAME, config_out, len(accepted), len(keys))
    return report
